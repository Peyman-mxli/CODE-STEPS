def get_rank(level):

    if level <= 10:
        return "Code Newbie"

    elif level <= 20:
        return "Bug Hunter"

    elif level <= 30:
        return "Script Builder"

    elif level <= 40:
        return "Logic Crafter"

    elif level <= 50:
        return "Code Warrior"

    elif level <= 60:
        return "Algorithm Master"

    elif level <= 70:
        return "System Architect"

    elif level <= 80:
        return "Code Overlord"

    elif level <= 90:
        return "Software Elite"

    elif level <= 100:
        return "Grand Developer"

    elif level <= 120:
        return "Legendary Engineer"

    elif level <= 140:
        return "Code Titan"

    elif level <= 160:
        return "Digital Warlord"

    elif level <= 180:
        return "Supreme Architect"

    else:
        return "Godlike Programmer"